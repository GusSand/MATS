# MAIN
# =============================================================================

def main():
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")

    print("=" * 70)
    print("Experiment 25: Functional Correctness Evaluation")
    print(f"Judge: {MODEL} (via OpenRouter)")
    print(f"Samples: {SAMPLES_PER_CONDITION} per condition × 4 conditions = 100 total")
    print(f"Timestamp: {timestamp}")
    print("=" * 70)

    # Initialize client
    client = OpenAI(api_key=API_KEY, base_url=BASE_URL)

    # Test API connectivity
    print("\nTesting API connectivity...")
    try:
        test_resp = client.chat.completions.create(
            model=MODEL,
            messages=[{"role": "user", "content": "Say OK"}],
            max_tokens=5,
        )
        print(f"  API OK: {test_resp.choices[0].message.content}")
    except Exception as e:
        print(f"  API ERROR: {e}")
        print("  Check API key and try again.")
        return

    # ── Load data ──────────────────────────────────────────────────────────

    print(f"\nLoading Mistral-7B fold results...")
    mistral_steered_all = load_fold_outputs(MISTRAL_FOLD_DIR, MISTRAL_TIMESTAMP, BEST_ALPHA)
    mistral_baseline_all = load_fold_outputs(MISTRAL_FOLD_DIR, MISTRAL_TIMESTAMP, BASELINE_ALPHA)
    print(f"  Steered (α={BEST_ALPHA}): {len(mistral_steered_all)} outputs")
    print(f"  Baseline (α=0.0): {len(mistral_baseline_all)} outputs")

    print(f"\nLoading Llama-8B fold results...")
    llama_steered_all = load_fold_outputs(LLAMA_FOLD_DIR, LLAMA_TIMESTAMP, BEST_ALPHA)
    llama_baseline_all = load_fold_outputs(LLAMA_FOLD_DIR, LLAMA_TIMESTAMP, BASELINE_ALPHA)
    print(f"  Steered (α={BEST_ALPHA}): {len(llama_steered_all)} outputs")
    print(f"  Baseline (α=0.0): {len(llama_baseline_all)} outputs")

    # ── Sample outputs ─────────────────────────────────────────────────────

    print(f"\nSampling {SAMPLES_PER_CONDITION} outputs per condition (seed={SEED})...")

    conditions = {
        "mistral7b_steered": sample_outputs(mistral_steered_all, SAMPLES_PER_CONDITION, SEED),
        "mistral7b_baseline": sample_outputs(mistral_baseline_all, SAMPLES_PER_CONDITION, SEED + 1),
        "llama8b_steered": sample_outputs(llama_steered_all, SAMPLES_PER_CONDITION, SEED + 2),
        "llama8b_baseline": sample_outputs(llama_baseline_all, SAMPLES_PER_CONDITION, SEED + 3),
    }

    for name, samples in conditions.items():
        avg_len = sum(s["output_length"] for s in samples) / len(samples) if samples else 0
        print(f"  {name}: {len(samples)} samples, avg output length: {avg_len:.0f} chars")

    # ── Evaluate with GPT-4o ──────────────────────────────────────────────

    all_results = {}
    total_evaluated = 0
    total_to_evaluate = sum(len(s) for s in conditions.values())

    for condition_name, samples in conditions.items():
        print(f"\n{'─'*50}")
        print(f"Evaluating: {condition_name} ({len(samples)} samples)")
        print(f"{'─'*50}")

        condition_results = []
        for i, sample in enumerate(samples):
            verdict = evaluate_output(client, sample["output"])
            total_evaluated += 1

            result = {
                "id": sample["id"],
                "fold_id": sample["fold_id"],
                "base_id": sample["base_id"],
                "output": sample["output"],
                "output_length": sample["output_length"],
                "strict_label": sample["strict_label"],
                "verdict": verdict,
            }
            condition_results.append(result)

            print(f"  [{total_evaluated}/{total_to_evaluate}] {sample['id'][:40]:40s} | "
                  f"len={sample['output_length']:4d} | {verdict}")

            # Rate limiting
            time.sleep(0.5)

        all_results[condition_name] = condition_results

    # ── Aggregate results ─────────────────────────────────────────────────

    print(f"\n{'='*70}")
    print("AGGREGATE RESULTS")
    print(f"{'='*70}")

    summary = {}
    for condition_name, results in all_results.items():
        n = len(results)
        counts = {}
        for r in results:
            v = r["verdict"]
            counts[v] = counts.get(v, 0) + 1

        correct_rate = counts.get("CORRECT", 0) / n if n > 0 else 0
        partial_rate = counts.get("PARTIALLY_CORRECT", 0) / n if n > 0 else 0
        incorrect_rate = counts.get("INCORRECT", 0) / n if n > 0 else 0
        incomplete_rate = counts.get("INCOMPLETE", 0) / n if n > 0 else 0
        functional_rate = (counts.get("CORRECT", 0) + counts.get("PARTIALLY_CORRECT", 0)) / n if n > 0 else 0

        summary[condition_name] = {
            "n": n,
            "counts": counts,
            "correct_rate": correct_rate,
            "partially_correct_rate": partial_rate,
            "incorrect_rate": incorrect_rate,
            "incomplete_rate": incomplete_rate,
            "functional_rate": functional_rate,  # CORRECT + PARTIALLY_CORRECT
        }

    # Print table
    print(f"\n  {'Condition':<25} | {'N':>3} | {'CORRECT':>8} | {'PARTIAL':>8} | {'INCORRECT':>9} | {'INCOMPLETE':>10} | {'Functional':>10}")
    print(f"  {'-'*90}")
    for cond, s in summary.items():
        print(f"  {cond:<25} | {s['n']:>3} | {s['correct_rate']:>7.1%} | {s['partially_correct_rate']:>7.1%} | "
              f"{s['incorrect_rate']:>8.1%} | {s['incomplete_rate']:>9.1%} | {s['functional_rate']:>9.1%}")

    # 2x2 comparison table
    print(f"\n  2×2 Summary (Functional = CORRECT + PARTIALLY_CORRECT):")
    print(f"  {'Model':<15} | {'Baseline':>12} | {'Steered':>12} | {'Diff':>10}")
    print(f"  {'-'*55}")

    for model_name in ["mistral7b", "llama8b"]:
        baseline = summary.get(f"{model_name}_baseline", {}).get("functional_rate", 0)
        steered = summary.get(f"{model_name}_steered", {}).get("functional_rate", 0)
        diff = steered - baseline
        print(f"  {model_name:<15} | {baseline:>11.1%} | {steered:>11.1%} | {diff:>+9.1%}")

    # ── Note on truncation ────────────────────────────────────────────────

    print(f"\n  NOTE: Some outputs are truncated (Llama-8B capped at 500 chars).")
    print(f"  This may inflate INCOMPLETE ratings on steered outputs if steering")
    print(f"  produces longer but still valid code.")

    # ── Save results ──────────────────────────────────────────────────────

    output = {
        "timestamp": timestamp,
        "experiment": "functional_correctness_evaluation",
        "judge_model": MODEL,
        "judge_api": "OpenRouter",
        "best_alpha": BEST_ALPHA,
        "baseline_alpha": BASELINE_ALPHA,
        "samples_per_condition": SAMPLES_PER_CONDITION,
        "seed": SEED,
        "truncation_note": "Llama-8B outputs truncated to 500 chars; Mistral-7B varies. May bias toward INCOMPLETE.",
        "summary": summary,
        "per_output_results": all_results,
        "source_files": {
            "mistral7b": str(MISTRAL_FOLD_DIR),
            "llama8b": str(LLAMA_FOLD_DIR),
        },
    }

    results_path = RESULTS_DIR / f"correctness_results_{timestamp}.json"
    with open(results_path, "w") as f:
        json.dump(output, f, indent=2, default=str)
    print(f"\nResults saved: {results_path}")

    print(f"\nExperiment complete. {total_evaluated} outputs evaluated.")


if __name__ == "__main__":
    main()
