def main():
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")

    print("=" * 70)
    print("Experiment 25c: Functional Correctness at α=3.0 (Llama-8B)")
    print(f"Model: {MODEL_NAME}")
    print(f"Layer: {STEERING_LAYER}, Alpha: {ALPHA}")
    print(f"Max new tokens: {MAX_NEW_TOKENS} (NO truncation)")
    print(f"Judge: {JUDGE_MODEL}")
    print(f"Timestamp: {timestamp}")
    print("=" * 70)

    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    # ── Load Exp 25b results ─────────────────────────────────────────────

    print("\nLoading Exp 25b results...")
    with open(EXP25B_RESULTS) as f:
        exp25b = json.load(f)

    steered_ids = [r["id"] for r in exp25b["steered_outputs"]]
    print(f"  Using same {len(steered_ids)} steered prompt IDs from 25b")

    # Store 25b results for comparison
