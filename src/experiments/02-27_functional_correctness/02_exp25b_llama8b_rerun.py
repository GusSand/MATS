def main():
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")

    print("=" * 70)
    print("Experiment 25b: Functional Correctness Re-evaluation (Llama-8B)")
    print(f"Model: {MODEL_NAME}")
    print(f"Layer: {STEERING_LAYER}, Alpha: {ALPHA_STEERED}")
    print(f"Max new tokens: {MAX_NEW_TOKENS} (NO truncation)")
    print(f"Judge: {JUDGE_MODEL}")
    print(f"Timestamp: {timestamp}")
    print("=" * 70)

    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    # ── Load Exp 25 prompt IDs ────────────────────────────────────────────

    print("\nLoading Exp 25 prompt IDs...")
    with open(EXP25_RESULTS) as f:
        exp25 = json.load(f)

    steered_ids = [r["id"] for r in exp25["per_output_results"]["llama8b_steered"]]
    baseline_ids = [r["id"] for r in exp25["per_output_results"]["llama8b_baseline"]]
    print(f"  Steered IDs: {len(steered_ids)}")
    print(f"  Baseline IDs: {len(baseline_ids)}")

    # ── Load dataset ──────────────────────────────────────────────────────

    print("\nLoading dataset...")
    with open(DATASET_PATH) as f:
        dataset = [json.loads(line) for line in f]

    # Build lookup by ID
    dataset_by_id = {item["id"]: item for item in dataset}
    print(f"  {len(dataset)} pairs loaded")

    # Verify all IDs exist in dataset
    all_ids = set(steered_ids + baseline_ids)
    missing = all_ids - set(dataset_by_id.keys())
    if missing:
        print(f"  WARNING: {len(missing)} IDs not found in dataset: {missing}")

    # ── Load model ────────────────────────────────────────────────────────

    print("\nLoading model...")
    tokenizer = AutoTokenizer.from_pretrained(MODEL_NAME)
    tokenizer.pad_token = tokenizer.eos_token

    model = AutoModelForCausalLM.from_pretrained(
        MODEL_NAME,
        torch_dtype=torch.float16,
        device_map="auto",
    )
    model.eval()
    print(f"  Model loaded: {model.config.num_hidden_layers} layers, "
          f"{model.config.hidden_size} hidden dim")

    # ── Extract activations for LOBO directions ──────────────────────────

    print("\nExtracting activations for LOBO directions...")

    # Load metadata for LOBO splits
    with open(METADATA_PATH) as f:
        metadata = json.load(f)

    # Build prompts in same order as metadata: vulnerable (0-104), secure (105-209)
    vuln_prompts = [dataset_by_id[m["id"]]["vulnerable"] for m in metadata["vulnerable_metadata"]]
    sec_prompts = [dataset_by_id[m["id"]]["secure"] for m in metadata["secure_metadata"]]
    all_prompts = vuln_prompts + sec_prompts

    print(f"  Extracting {len(all_prompts)} activations at L{STEERING_LAYER}...")
    X = extract_activations(model, tokenizer, all_prompts, STEERING_LAYER, device)
    y = np.array([0] * len(vuln_prompts) + [1] * len(sec_prompts))
    print(f"  Activations: {X.shape}, Labels: {y.shape}")

    # Compute LOBO directions for each fold
    print("\nComputing LOBO fold directions...")
    fold_directions = {}
    for base_id in BASE_IDS:
        direction = compute_lobo_direction(X, y, metadata, base_id)
        norm = np.linalg.norm(direction)
        fold_directions[base_id] = direction
        print(f"  {base_id}: norm={norm:.4f}")

    # ── Generate steered outputs ─────────────────────────────────────────

    print(f"\n{'─'*50}")
    print(f"Generating steered outputs (α={ALPHA_STEERED}, {len(steered_ids)} prompts)")
    print(f"{'─'*50}")

    steered_outputs = []
    for i, prompt_id in enumerate(steered_ids):
        item = dataset_by_id[prompt_id]
        base_id = item["base_id"]
        direction = fold_directions[base_id]

        output = generate_with_steering(
            model, tokenizer, item["vulnerable"],
            direction, STEERING_LAYER, ALPHA_STEERED, device,
        )

        steered_outputs.append({
            "id": prompt_id,
            "base_id": base_id,
            "output": output,
            "output_length": len(output),
        })

        print(f"  [{i+1}/{len(steered_ids)}] {prompt_id[:40]:40s} | len={len(output):5d}")

    # ── Generate baseline outputs ────────────────────────────────────────

    print(f"\n{'─'*50}")
    print(f"Generating baseline outputs (α={ALPHA_BASELINE}, {len(baseline_ids)} prompts)")
    print(f"{'─'*50}")

    baseline_outputs = []
    for i, prompt_id in enumerate(baseline_ids):
        item = dataset_by_id[prompt_id]

        output = generate_with_steering(
            model, tokenizer, item["vulnerable"],
            None, STEERING_LAYER, ALPHA_BASELINE, device,
        )

        baseline_outputs.append({
            "id": prompt_id,
            "base_id": item["base_id"],
            "output": output,
            "output_length": len(output),
        })

        print(f"  [{i+1}/{len(baseline_ids)}] {prompt_id[:40]:40s} | len={len(output):5d}")

    # ── Free GPU memory ──────────────────────────────────────────────────

    print("\nFreeing GPU memory...")
    del model
    torch.cuda.empty_cache()

    # ── Output length statistics ─────────────────────────────────────────

    steered_lens = [o["output_length"] for o in steered_outputs]
    baseline_lens = [o["output_length"] for o in baseline_outputs]

    print(f"\nOutput length statistics (NO truncation):")
    print(f"  Steered:  min={min(steered_lens)}, max={max(steered_lens)}, "
          f"avg={sum(steered_lens)/len(steered_lens):.0f}, "
          f"n_over_500={sum(1 for l in steered_lens if l > 500)}")
    print(f"  Baseline: min={min(baseline_lens)}, max={max(baseline_lens)}, "
          f"avg={sum(baseline_lens)/len(baseline_lens):.0f}, "
          f"n_over_500={sum(1 for l in baseline_lens if l > 500)}")

    # ── Evaluate with GPT-4o ─────────────────────────────────────────────

    print(f"\n{'─'*50}")
    print("Evaluating with GPT-4o...")
    print(f"{'─'*50}")

    client = OpenAI(api_key=API_KEY, base_url=BASE_URL)

    # Test connectivity
    try:
        test_resp = client.chat.completions.create(
            model=JUDGE_MODEL,
            messages=[{"role": "user", "content": "Say OK"}],
            max_tokens=5,
        )
        print(f"  API OK: {test_resp.choices[0].message.content}")
    except Exception as e:
        print(f"  API ERROR: {e}")
        print("  Saving generation results without evaluation...")
        # Save raw outputs even if API fails
        raw_output = {
            "timestamp": timestamp,
            "steered_outputs": steered_outputs,
            "baseline_outputs": baseline_outputs,
        }
        raw_path = RESULTS_DIR / f"exp25b_raw_outputs_{timestamp}.json"
        with open(raw_path, "w") as f:
            json.dump(raw_output, f, indent=2)
        print(f"  Raw outputs saved: {raw_path}")
        return

    total_evaluated = 0
    total_to_evaluate = len(steered_outputs) + len(baseline_outputs)

    # Evaluate steered
    print(f"\n  Evaluating steered ({len(steered_outputs)} samples):")
    for item in steered_outputs:
        verdict = evaluate_output(client, item["output"])
        item["verdict"] = verdict
        total_evaluated += 1
        print(f"    [{total_evaluated}/{total_to_evaluate}] {item['id'][:40]:40s} | "
              f"len={item['output_length']:5d} | {verdict}")
        time.sleep(0.5)

    # Evaluate baseline
    print(f"\n  Evaluating baseline ({len(baseline_outputs)} samples):")
    for item in baseline_outputs:
        verdict = evaluate_output(client, item["output"])
        item["verdict"] = verdict
        total_evaluated += 1
        print(f"    [{total_evaluated}/{total_to_evaluate}] {item['id'][:40]:40s} | "
              f"len={item['output_length']:5d} | {verdict}")
        time.sleep(0.5)

    # ── Aggregate results ────────────────────────────────────────────────

    print(f"\n{'='*70}")
    print("AGGREGATE RESULTS — Exp 25b (Llama-8B, untruncated)")
    print(f"{'='*70}")

    for label, outputs in [("steered", steered_outputs), ("baseline", baseline_outputs)]:
        n = len(outputs)
        counts = {}
        for o in outputs:
            v = o["verdict"]
            counts[v] = counts.get(v, 0) + 1

        correct = counts.get("CORRECT", 0)
        partial = counts.get("PARTIALLY_CORRECT", 0)
        incorrect = counts.get("INCORRECT", 0)
        incomplete = counts.get("INCOMPLETE", 0)
        functional = correct + partial

        print(f"\n  {label} (α={'3.5' if label == 'steered' else '0.0'}):")
        print(f"    N={n}, CORRECT={correct} ({correct/n:.1%}), "
              f"PARTIAL={partial} ({partial/n:.1%}), "
              f"INCORRECT={incorrect} ({incorrect/n:.1%}), "
              f"INCOMPLETE={incomplete} ({incomplete/n:.1%})")
        print(f"    Functional (CORRECT+PARTIAL): {functional} ({functional/n:.1%})")

    # Compare with Exp 25
    print(f"\n  Comparison with Exp 25 (truncated at 500 chars):")
    print(f"  {'Condition':<30} | {'Exp 25':>10} | {'Exp 25b':>10} | {'Diff':>8}")
    print(f"  {'-'*65}")

    exp25_steered_func = exp25["summary"]["llama8b_steered"]["functional_rate"]
    exp25_baseline_func = exp25["summary"]["llama8b_baseline"]["functional_rate"]

    steered_func = sum(1 for o in steered_outputs if o["verdict"] in ("CORRECT", "PARTIALLY_CORRECT")) / len(steered_outputs)
    baseline_func = sum(1 for o in baseline_outputs if o["verdict"] in ("CORRECT", "PARTIALLY_CORRECT")) / len(baseline_outputs)

    print(f"  {'Llama-8B steered (α=3.5)':<30} | {exp25_steered_func:>9.1%} | {steered_func:>9.1%} | {steered_func - exp25_steered_func:>+7.1%}")
    print(f"  {'Llama-8B baseline (α=0.0)':<30} | {exp25_baseline_func:>9.1%} | {baseline_func:>9.1%} | {baseline_func - exp25_baseline_func:>+7.1%}")
    print(f"\n  Steered vs Baseline diff:")
    print(f"    Exp 25:  {exp25_steered_func - exp25_baseline_func:>+.1%}")
    print(f"    Exp 25b: {steered_func - baseline_func:>+.1%}")

    # ── Save results ─────────────────────────────────────────────────────

    output_data = {
        "timestamp": timestamp,
        "experiment": "exp25b_functional_correctness_llama8b_untruncated",
        "model": MODEL_NAME,
        "steering_layer": STEERING_LAYER,
        "alpha_steered": ALPHA_STEERED,
        "alpha_baseline": ALPHA_BASELINE,
        "max_new_tokens": MAX_NEW_TOKENS,
        "temperature": TEMPERATURE,
        "top_p": TOP_P,
        "judge_model": JUDGE_MODEL,
        "n_steered": len(steered_outputs),
        "n_baseline": len(baseline_outputs),
        "output_length_stats": {
            "steered": {
                "min": min(steered_lens),
                "max": max(steered_lens),
                "mean": sum(steered_lens) / len(steered_lens),
                "n_over_500": sum(1 for l in steered_lens if l > 500),
            },
            "baseline": {
                "min": min(baseline_lens),
                "max": max(baseline_lens),
                "mean": sum(baseline_lens) / len(baseline_lens),
                "n_over_500": sum(1 for l in baseline_lens if l > 500),
            },
        },
        "summary": {
            "steered": {
                "n": len(steered_outputs),
                "counts": {v: sum(1 for o in steered_outputs if o["verdict"] == v)
                           for v in ["CORRECT", "PARTIALLY_CORRECT", "INCORRECT", "INCOMPLETE", "ERROR"]
                           if any(o["verdict"] == v for o in steered_outputs)},
                "functional_rate": steered_func,
            },
            "baseline": {
                "n": len(baseline_outputs),
                "counts": {v: sum(1 for o in baseline_outputs if o["verdict"] == v)
                           for v in ["CORRECT", "PARTIALLY_CORRECT", "INCORRECT", "INCOMPLETE", "ERROR"]
                           if any(o["verdict"] == v for o in baseline_outputs)},
                "functional_rate": baseline_func,
            },
        },
        "comparison_with_exp25": {
            "exp25_steered_functional": exp25_steered_func,
            "exp25_baseline_functional": exp25_baseline_func,
            "exp25b_steered_functional": steered_func,
            "exp25b_baseline_functional": baseline_func,
        },
        "fold_direction_norms": {k: float(np.linalg.norm(v)) for k, v in fold_directions.items()},
        "steered_outputs": steered_outputs,
        "baseline_outputs": baseline_outputs,
    }

    results_path = RESULTS_DIR / f"exp25b_correctness_results_{timestamp}.json"
    with open(results_path, "w") as f:
        json.dump(output_data, f, indent=2, default=str)
    print(f"\nResults saved: {results_path}")

    print(f"\nExperiment 25b complete. {total_evaluated} outputs evaluated.")


if __name__ == "__main__":
    main()
