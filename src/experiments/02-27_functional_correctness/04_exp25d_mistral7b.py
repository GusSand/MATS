# =============================================================================
# DEGENERATION DETECTION (same as 25c)
# =============================================================================

def detect_degeneration(text):
    """Detect token repetition loops in generated text."""
    patterns_found = []

    # Repeated short phrases (3+ consecutive repeats of 3-30 char spans)
    match = re.search(r'(.{3,30})\1{2,}', text)
    if match:
        patterns_found.append(f"repeated phrase: '{match.group(1)[:40]}' x{len(match.group(0))//len(match.group(1))}")

    # Known degeneration patterns
    known_patterns = [
        (r'(?:snsnprint|snprint\s+function)', "snsnprint/snprint repetition"),
        (r'(?:Snippets?\s+of\s+XML\s+snippets?\s+){2,}', "Snippets of XML repetition"),
        (r'(?:Security\s+Security\s+){2,}', "Security Security repetition"),
        (r'(?:The\s+buffer\s+){4,}', "The buffer repetition"),
        (r'(?:The\s+snippet\s+){4,}', "The snippet repetition"),
    ]
    for pattern, desc in known_patterns:
        if re.search(pattern, text, re.IGNORECASE):
            patterns_found.append(desc)

    # Large duplicate blocks
    if len(text) > 300:
        half = len(text) // 2
        for start in range(0, min(half, 500), 50):
            block = text[start:start+100]
            if block in text[start+100:]:
                patterns_found.append(f"large block duplication (100+ chars at pos {start})")
                break

    return {
        "is_degenerate": len(patterns_found) > 0,
        "patterns_found": patterns_found,
    }


# =============================================================================
# LOBO DIRECTION COMPUTATION (from pre-computed activations)
# =============================================================================

def compute_lobo_direction(X, y, metadata, held_out_base_id):
    """Compute LOBO direction holding out one base_id."""
    train_vuln = [i for i, m in enumerate(metadata['vulnerable_metadata'])
                  if m['base_id'] != held_out_base_id]
    train_sec = [i + len(metadata['vulnerable_metadata'])
                 for i, m in enumerate(metadata['secure_metadata'])
                 if m['base_id'] != held_out_base_id]

    train_indices = train_vuln + train_sec
    X_train = X[train_indices]
    y_train = y[train_indices]

    secure_mean = X_train[y_train == 1].mean(axis=0)
    vulnerable_mean = X_train[y_train == 0].mean(axis=0)

    direction = secure_mean - vulnerable_mean
    return direction.astype(np.float32)


# =============================================================================
# GENERATION WITH STEERING
# =============================================================================

def generate_with_steering(model, tokenizer, prompt, direction, layer, alpha, device):
    """Generate with activation steering at specified layer."""
    if alpha == 0.0 or direction is None:
        # Baseline: no steering
        inputs = tokenizer(prompt, return_tensors="pt").to(device)
        input_len = inputs.input_ids.shape[1]
        with torch.no_grad():
            outputs = model.generate(
                **inputs,
                max_new_tokens=MAX_NEW_TOKENS,
                temperature=TEMPERATURE,
                do_sample=True,
                top_p=TOP_P,
                pad_token_id=tokenizer.pad_token_id,
            )
        new_tokens = outputs[0][input_len:]
        return tokenizer.decode(new_tokens, skip_special_tokens=True)

    direction_tensor = torch.tensor(direction, dtype=torch.float16).to(device)

    def steering_hook(module, input, output):
        if isinstance(output, tuple):
            h = output[0]
        else:
            h = output
        h[:, -1, :] = h[:, -1, :] + alpha * direction_tensor
        if isinstance(output, tuple):
            return (h,) + output[1:]
        return h

    target_layer = model.model.layers[layer]
    handle = target_layer.register_forward_hook(steering_hook)

    inputs = tokenizer(prompt, return_tensors="pt").to(device)
    input_len = inputs.input_ids.shape[1]

    with torch.no_grad():
        outputs = model.generate(
            **inputs,
            max_new_tokens=MAX_NEW_TOKENS,
            temperature=TEMPERATURE,
            do_sample=True,
            top_p=TOP_P,
            pad_token_id=tokenizer.pad_token_id,
        )

    handle.remove()

    new_tokens = outputs[0][input_len:]
    return tokenizer.decode(new_tokens, skip_special_tokens=True)


# =============================================================================
# GPT-4o JUDGE (identical to 25b)
# =============================================================================

def evaluate_output(client, code_text, retries=3):
    """Ask GPT-4o to judge functional correctness."""
    prompt = JUDGE_PROMPT.format(output=code_text)

    for attempt in range(retries):
        try:
            response = client.chat.completions.create(
                model=JUDGE_MODEL,
                messages=[{"role": "user", "content": prompt}],
                max_tokens=10,
                temperature=0.0,
            )
            verdict = response.choices[0].message.content.strip().upper()

            valid = {"CORRECT", "PARTIALLY_CORRECT", "INCORRECT", "INCOMPLETE"}
            if verdict in valid:
                return verdict
            for v in valid:
                if v in verdict:
                    return v

            print(f"    Unexpected verdict: '{verdict}', retrying...")
        except Exception as e:
            print(f"    API error (attempt {attempt+1}): {e}")
            if attempt < retries - 1:
                time.sleep(2 ** attempt)

    return "ERROR"


