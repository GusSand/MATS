#!/usr/bin/env python3
"""
Experiment 27 — Evaluation only.

Loads raw outputs from 05_exp27_neutral_correctness.py and evaluates with GPT-4o.
Uses OPENROUTER_API_KEY from environment.
"""

import json
import os
import time
from pathlib import Path
from datetime import datetime
from collections import Counter
from openai import OpenAI

# =============================================================================
# CONFIG
# =============================================================================

SCRIPT_DIR = Path(__file__).parent
RESULTS_DIR = SCRIPT_DIR / "results"

RAW_OUTPUTS_PATH = RESULTS_DIR / "exp27_raw_outputs_20260227_234501.json"

# Exp 25b/25d for adversarial comparison
EXP25B_RESULTS = RESULTS_DIR / "exp25b_correctness_results_20260227_180052.json"
EXP25D_RESULTS = RESULTS_DIR / "correctness_25d_20260227_195601.json"

API_KEY = os.environ.get("OPENAI_API_KEY", "")
BASE_URL = None  # Use OpenAI directly
JUDGE_MODEL = "gpt-4o-2024-05-13"

# Model configs (must match generation)
LLAMA_ALPHA = 3.0
MISTRAL_ALPHA = 3.5
ALPHA_BASELINE = 0.0

JUDGE_PROMPT = """You are a C programming expert evaluating code correctness.

The following C code was generated by an LLM in response to a coding prompt.
Evaluate whether the code is functionally correct — i.e., would it compile
and correctly implement the intended functionality, ignoring any security
considerations.

Rate as one of:
- CORRECT: Code would compile and correctly implement the intended function
- PARTIALLY_CORRECT: Code has minor issues but core logic is sound
- INCORRECT: Code has significant logical errors or would not compile
- INCOMPLETE: Code is truncated or missing essential parts

Code:
{output}

Respond with exactly one word: CORRECT, PARTIALLY_CORRECT, INCORRECT, or INCOMPLETE."""


def evaluate_output(client, code_text, retries=3):
    """Ask GPT-4o to judge functional correctness."""
    prompt = JUDGE_PROMPT.format(output=code_text)

    for attempt in range(retries):
        try:
            response = client.chat.completions.create(
                model=JUDGE_MODEL,
                messages=[{"role": "user", "content": prompt}],
                max_tokens=10,
                temperature=0.0,
            )
            verdict = response.choices[0].message.content.strip().upper()

            valid = {"CORRECT", "PARTIALLY_CORRECT", "INCORRECT", "INCOMPLETE"}
            if verdict in valid:
                return verdict
            for v in valid:
                if v in verdict:
                    return v

            print(f"    Unexpected verdict: '{verdict}', retrying...")
        except Exception as e:
            print(f"    API error (attempt {attempt+1}): {e}")
            if attempt < retries - 1:
                time.sleep(2 ** attempt)

    return "ERROR"


def compute_summary(outputs, label):
    n = len(outputs)
    counts = Counter(o["verdict"] for o in outputs)
    correct = counts.get("CORRECT", 0)
    partial = counts.get("PARTIALLY_CORRECT", 0)
    incorrect = counts.get("INCORRECT", 0)
    incomplete = counts.get("INCOMPLETE", 0)
    error = counts.get("ERROR", 0)
    functional = correct + partial
    functional_rate = functional / n if n > 0 else 0

    degen_count = sum(1 for o in outputs
                      if o.get("degeneration", {}).get("is_degenerate", False))

    print(f"\n  {label} (N={n}):")
    print(f"    CORRECT={correct} ({correct/n:.1%}), "
          f"PARTIAL={partial} ({partial/n:.1%}), "
          f"INCORRECT={incorrect} ({incorrect/n:.1%}), "
          f"INCOMPLETE={incomplete} ({incomplete/n:.1%})"
          + (f", ERROR={error}" if error else ""))
    print(f"    Functional rate: {functional}/{n} = {functional_rate:.1%}")
    if degen_count > 0:
        print(f"    Degenerate: {degen_count}/{n}")

    return {
        "n": n,
        "counts": dict(counts),
        "functional_rate": functional_rate,
        "degenerate_count": degen_count,
    }


def main():
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")

    print("=" * 70)
    print("Experiment 27 — Evaluation Phase (from saved raw outputs)")
    print(f"Judge: {JUDGE_MODEL}")
    print(f"Timestamp: {timestamp}")
    print("=" * 70)

    # Load raw outputs
    print("\nLoading raw outputs...")
    with open(RAW_OUTPUTS_PATH) as f:
        raw = json.load(f)

    llama_steered = raw["llama_steered"]
    llama_baseline = raw["llama_baseline"]
    mistral_steered = raw["mistral_steered"]
    mistral_baseline = raw["mistral_baseline"]

    print(f"  Llama steered:   {len(llama_steered)}")
    print(f"  Llama baseline:  {len(llama_baseline)}")
    print(f"  Mistral steered: {len(mistral_steered)}")
    print(f"  Mistral baseline:{len(mistral_baseline)}")

    # Connect to API
    client_kwargs = {"api_key": API_KEY}
    if BASE_URL:
        client_kwargs["base_url"] = BASE_URL
    client = OpenAI(**client_kwargs)

    try:
        test_resp = client.chat.completions.create(
            model=JUDGE_MODEL,
            messages=[{"role": "user", "content": "Say OK"}],
            max_tokens=5,
        )
        print(f"  API OK: {test_resp.choices[0].message.content}")
    except Exception as e:
        print(f"  API ERROR: {e}")
        return

    # Evaluate all
    all_groups = [
        ("Llama-8B steered", llama_steered),
        ("Llama-8B baseline", llama_baseline),
        ("Mistral-7B steered", mistral_steered),
        ("Mistral-7B baseline", mistral_baseline),
    ]

    total_evaluated = 0
    total_to_evaluate = sum(len(g) for _, g in all_groups)

    for group_name, outputs in all_groups:
        print(f"\n  Evaluating {group_name} ({len(outputs)} samples):")
        for item in outputs:
            verdict = evaluate_output(client, item["output"])
            item["verdict"] = verdict
            total_evaluated += 1
            print(f"    [{total_evaluated}/{total_to_evaluate}] "
                  f"{item['id']:25s} | len={item['output_length']:5d} | {verdict}")
            time.sleep(0.5)

    # Results
    print(f"\n{'='*70}")
    print("RESULTS")
    print(f"{'='*70}")

    llama_steered_summary = compute_summary(llama_steered, f"Llama-8B steered (α={LLAMA_ALPHA})")
    llama_baseline_summary = compute_summary(llama_baseline, f"Llama-8B baseline (α={ALPHA_BASELINE})")
    mistral_steered_summary = compute_summary(mistral_steered, f"Mistral-7B steered (α={MISTRAL_ALPHA})")
    mistral_baseline_summary = compute_summary(mistral_baseline, f"Mistral-7B baseline (α={ALPHA_BASELINE})")

    llama_penalty = llama_steered_summary["functional_rate"] - llama_baseline_summary["functional_rate"]
    mistral_penalty = mistral_steered_summary["functional_rate"] - mistral_baseline_summary["functional_rate"]

    print(f"\n{'─'*50}")
    print(f"CORRECTNESS PENALTY (neutral prompts):")
    print(f"  Llama-8B:   {llama_penalty:+.1%} "
          f"({llama_steered_summary['functional_rate']:.1%} steered vs "
          f"{llama_baseline_summary['functional_rate']:.1%} baseline)")
    print(f"  Mistral-7B: {mistral_penalty:+.1%} "
          f"({mistral_steered_summary['functional_rate']:.1%} steered vs "
          f"{mistral_baseline_summary['functional_rate']:.1%} baseline)")

    # Adversarial comparison
    print(f"\n{'─'*50}")
    print("COMPARISON: Neutral vs Adversarial Correctness Penalty")
    print(f"{'─'*50}")

    adv_llama_penalty = None
    adv_mistral_penalty = None

    if EXP25B_RESULTS.exists():
        with open(EXP25B_RESULTS) as f:
            exp25b = json.load(f)
        # Exp 25b stores Llama results in summary.steered/baseline
        adv_llama_penalty = (exp25b["summary"]["steered"]["functional_rate"]
                             - exp25b["summary"]["baseline"]["functional_rate"])

    if EXP25D_RESULTS.exists():
        with open(EXP25D_RESULTS) as f:
            exp25d = json.load(f)
        adv_mistral_penalty = exp25d["cross_model_comparison"]["mistral_correctness_penalty"]

    print(f"\n  {'Model':<12} | {'Neutral (Exp 27)':>18} | {'Adversarial (25b/d)':>20}")
    print(f"  {'-'*56}")
    if adv_llama_penalty is not None:
        print(f"  {'Llama-8B':<12} | {llama_penalty:>+17.1%} | {adv_llama_penalty:>+19.1%}")
    else:
        print(f"  {'Llama-8B':<12} | {llama_penalty:>+17.1%} | {'N/A':>20}")
    if adv_mistral_penalty is not None:
        print(f"  {'Mistral-7B':<12} | {mistral_penalty:>+17.1%} | {adv_mistral_penalty:>+19.1%}")
    else:
        print(f"  {'Mistral-7B':<12} | {mistral_penalty:>+17.1%} | {'N/A':>20}")

    # Degeneration details
    print(f"\n{'─'*50}")
    print("DEGENERATION DETAILS (steered outputs only)")
    print(f"{'─'*50}")

    for model_label, steered in [("Llama-8B", llama_steered), ("Mistral-7B", mistral_steered)]:
        degen = [o for o in steered if o.get("degeneration", {}).get("is_degenerate", False)]
        print(f"\n  {model_label}: {len(degen)}/{len(steered)} degenerate")
        for o in degen:
            print(f"    {o['id']}: {o['degeneration']['patterns_found']}")

    # Output length stats
    def len_stats(outputs):
        lens = [o["output_length"] for o in outputs]
        return {
            "min": min(lens), "max": max(lens),
            "mean": round(sum(lens) / len(lens), 1),
            "n_over_500": sum(1 for l in lens if l > 500),
        }

    # Save final results
    output_data = {
        "timestamp": timestamp,
        "experiment": "exp27_functional_correctness_neutral_prompts",
        "prompt_type": "neutral",
        "n_prompts": len(llama_steered),
        "judge_model": JUDGE_MODEL,
        "generation_timestamp": raw["timestamp"],
        "models": {
            "llama": {
                "name": "meta-llama/Meta-Llama-3.1-8B-Instruct",
                "steering_layer": 31,
                "alpha_steered": LLAMA_ALPHA,
                "alpha_baseline": ALPHA_BASELINE,
            },
            "mistral": {
                "name": "mistralai/Mistral-7B-Instruct-v0.3",
                "steering_layer": 31,
                "alpha_steered": MISTRAL_ALPHA,
                "alpha_baseline": ALPHA_BASELINE,
            },
        },
        "summary": {
            "llama_steered": llama_steered_summary,
            "llama_baseline": llama_baseline_summary,
            "mistral_steered": mistral_steered_summary,
            "mistral_baseline": mistral_baseline_summary,
        },
        "correctness_penalty": {
            "llama_neutral": llama_penalty,
            "mistral_neutral": mistral_penalty,
            "llama_adversarial_25b": adv_llama_penalty,
            "mistral_adversarial_25d": adv_mistral_penalty,
        },
        "output_length_stats": {
            "llama_steered": len_stats(llama_steered),
            "llama_baseline": len_stats(llama_baseline),
            "mistral_steered": len_stats(mistral_steered),
            "mistral_baseline": len_stats(mistral_baseline),
        },
        "degeneration": {
            "llama_steered": {
                "count": llama_steered_summary["degenerate_count"],
                "details": [
                    {"id": o["id"], "patterns": o["degeneration"]["patterns_found"]}
                    for o in llama_steered
                    if o.get("degeneration", {}).get("is_degenerate", False)
                ],
            },
            "mistral_steered": {
                "count": mistral_steered_summary["degenerate_count"],
                "details": [
                    {"id": o["id"], "patterns": o["degeneration"]["patterns_found"]}
                    for o in mistral_steered
                    if o.get("degeneration", {}).get("is_degenerate", False)
                ],
            },
        },
        "llama_steered_outputs": llama_steered,
        "llama_baseline_outputs": llama_baseline,
        "mistral_steered_outputs": mistral_steered,
        "mistral_baseline_outputs": mistral_baseline,
    }

    results_path = RESULTS_DIR / f"correctness_27_{timestamp}.json"
    with open(results_path, "w") as f:
        json.dump(output_data, f, indent=2, default=str)
    print(f"\nResults saved: {results_path}")
    print(f"\nExperiment 27 complete. {total_evaluated} outputs evaluated.")


if __name__ == "__main__":
    main()
