# HELPER: Run one model end-to-end
# =============================================================================

def run_model(model_name, alpha_steered, neutral_prompts, direction, device):
    """Load model, generate steered + baseline outputs on neutral prompts, free GPU."""
    print(f"\n{'='*70}")
    print(f"Loading {model_name}...")
    print(f"{'='*70}")

    tokenizer = AutoTokenizer.from_pretrained(model_name)
    tokenizer.pad_token = tokenizer.eos_token

    model = AutoModelForCausalLM.from_pretrained(
        model_name,
        torch_dtype=torch.float16,
        device_map="auto",
    )
    model.eval()
    print(f"  Model loaded: {model.config.num_hidden_layers} layers, "
          f"{model.config.hidden_size} hidden dim")

    # Generate steered outputs
    print(f"\n{'─'*50}")
    print(f"Generating steered outputs (α={alpha_steered}, {len(neutral_prompts)} prompts)")
    print(f"{'─'*50}")

    steered_outputs = []
    for i, prompt_data in enumerate(neutral_prompts):
        output = generate_with_steering(
            model, tokenizer, prompt_data["prompt"],
            direction, STEERING_LAYER, alpha_steered, device,
        )
        degen = detect_degeneration(output)

        steered_outputs.append({
            "id": prompt_data["id"],
            "cwe": prompt_data["cwe"],
            "description": prompt_data["description"],
            "output": output,
            "output_length": len(output),
            "degeneration": degen,
        })

        degen_flag = " [DEGEN]" if degen["is_degenerate"] else ""
        print(f"  [{i+1}/{len(neutral_prompts)}] {prompt_data['id']:25s} | "
              f"len={len(output):5d}{degen_flag}")

    # Generate baseline outputs
    print(f"\n{'─'*50}")
    print(f"Generating baseline outputs (α={ALPHA_BASELINE}, {len(neutral_prompts)} prompts)")
    print(f"{'─'*50}")

    baseline_outputs = []
    for i, prompt_data in enumerate(neutral_prompts):
        output = generate_with_steering(
            model, tokenizer, prompt_data["prompt"],
            None, STEERING_LAYER, ALPHA_BASELINE, device,
        )

        baseline_outputs.append({
            "id": prompt_data["id"],
            "cwe": prompt_data["cwe"],
            "description": prompt_data["description"],
            "output": output,
            "output_length": len(output),
        })

        print(f"  [{i+1}/{len(neutral_prompts)}] {prompt_data['id']:25s} | "
              f"len={len(output):5d}")

    # Free GPU
    print(f"\nFreeing GPU memory for {model_name}...")
    del model
    del tokenizer
    gc.collect()
    torch.cuda.empty_cache()

    return steered_outputs, baseline_outputs


